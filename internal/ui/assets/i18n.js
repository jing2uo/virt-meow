// lang is set from the Go side's locale (setLang), navigator's until then.
export let lang = (navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
export function setLang(l) { lang = l === "zh" ? "zh" : "en"; }

// t translates s and fills in {placeholders} from vars.
export function t(s, vars) {
  let out = lang === "zh" ? (ZH[s] ?? s) : (EN[s] ?? s);
  for (const [k, v] of Object.entries(vars || {})) out = out.replaceAll(`{${k}}`, v);
  return out;
}

// translate fills in elements marked data-t (text) and data-title (tooltip).
export function translate(root = document) {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  root.querySelectorAll("[data-t]").forEach((el) => { el.textContent = t(el.dataset.t); });
  root.querySelectorAll("[data-title]").forEach((el) => { el.title = t(el.dataset.title); });
  root.querySelectorAll("[data-label]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.label)); });
}
